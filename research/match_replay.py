from dataclasses import asdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "research"))

from fortnite_chest_counter import match_state as S
import match_scorecard as C


CACHE_SCHEMA = "match-cues-v1"
REPORT_SCHEMA = "match-replay-v1"


def load_json(path):
    path = Path(path)
    opener = gzip.open if path.suffix == ".gz" else open
    with opener(path, "rt", encoding="utf-8-sig") as stream:
        return json.load(stream)


def write_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    raw = (json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False, allow_nan=False) + "\n").encode("utf-8")
    if path.suffix == ".gz":
        raw = gzip.compress(raw, mtime=0)
    path.write_bytes(raw)


def sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def validate_rows(rows, name):
    if not isinstance(rows, list) or not rows:
        raise ValueError(f"{name}: no cue samples")
    previous = float("-inf")
    for row in rows:
        if not isinstance(row, list) or len(row) != 5:
            raise ValueError(f"{name}: each cue row must be [time, scores, health_pixels, black, frozen]")
        t, scores, hp, black, frozen = row
        if not C.number(t) or t < 0 or t <= previous:
            raise ValueError(f"{name}: cue timestamps must be finite, nonnegative and strictly increasing; split clock resets into separate sources")
        previous = t
        if not isinstance(scores, dict) or set(scores) - S.ALL_SIGNALS or not all(C.number(v) and 0 <= v <= 1 for v in scores.values()):
            raise ValueError(f"{name}: invalid cue scores")
        if not isinstance(hp, int) or isinstance(hp, bool) or hp < 0 or not isinstance(black, (bool, int)) or black not in (0, 1) or not isinstance(frozen, (bool, int)) or frozen not in (0, 1):
            raise ValueError(f"{name}: invalid health/picture evidence")
    return rows


def load_timelines(path):
    data = load_json(path)
    if not isinstance(data, dict) or not data:
        raise ValueError("cue cache must contain named sources")
    if "schema" in data:
        if data["schema"] != CACHE_SCHEMA or not isinstance(data.get("sources"), dict) or not data["sources"]:
            raise ValueError("unsupported/empty cue cache")
        sources = data["sources"]
        for name, source in sources.items():
            if not isinstance(source, dict) or not isinstance(source.get("provenance"), dict):
                raise ValueError(f"{name}: cache source lacks provenance")
            validate_rows(source.get("samples"), name)
            if not C.number(source.get("finish_t")) or source["finish_t"] < source["samples"][-1][0]:
                raise ValueError(f"{name}: invalid cache finish time")
        return sources
    # The M2 fixture predates a provenance wrapper. Do not present it as a fresh
    # decode, or as cryptographic proof that today's footage/reader is identical.
    return {name: {"samples": validate_rows(rows, name), "finish_t": rows[-1][0] + 1,
                   "provenance": {"kind": "legacy_fixture", "cache_sha256": sha256(path), "source_id": name}}
            for name, rows in data.items()}


def named_paths(values):
    result = {}
    for value in values:
        name, separator, path = value.partition("=")
        if not separator or not name or not path or name in result:
            raise ValueError("use unique SOURCE=PATH arguments")
        result[name] = Path(path).resolve()
    return result


def playlist_files(path):
    """Only the local-file playlists generated by diagnostic capture are supported."""
    path = Path(path)
    if path.suffix.lower() != ".ffconcat":
        if not path.is_file():
            raise ValueError(f"video does not exist: {path}")
        return [path]
    files = [path]
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or line == "ffconcat version 1.0":
            continue
        parts = shlex.split(line)
        if len(parts) != 2 or parts[0] != "file" or "://" in parts[1]:
            raise ValueError(f"unsupported playlist directive in {path}: {line}")
        child = (path.parent / parts[1]).resolve()
        if not child.is_file() or child.suffix.lower() == ".ffconcat":
            raise ValueError(f"missing/nested playlist segment: {child}")
        files.append(child)
    if len(files) == 1:
        raise ValueError(f"empty playlist: {path}")
    return files


def capture_sources(folder):
    """Each kept clip starts a fresh state machine; missing segments are never bridged.

    Ground truth is in clip video seconds, as in M1/M2. Reject dropped-frame or
    stalled captures whose encoded clock would conceal a material live-time gap.
    """
    folder = Path(folder).resolve()
    info = load_json(folder / "capture.json")
    clips = load_json(folder / "video" / "clips.json")
    fps = info.get("fps")
    if not C.number(fps) or fps <= 0 or info.get("frames_not_recorded", 0):
        raise ValueError("capture has dropped frames or invalid FPS; use reviewed, separately timed clips")
    with (folder / "timeline.csv").open(encoding="utf-8-sig", newline="") as stream:
        times = [float(row["live_t"]) for row in csv.DictReader(stream)]
    out = {}
    for index, clip in enumerate(clips, 1):
        start, end = clip["start"], clip["end"]
        if not C.number(start) or not C.number(end) or start < 0 or end <= start:
            raise ValueError("invalid capture clip boundaries")
        first, last = round(start * fps), round(end * fps)
        if first >= len(times) or last > len(times) + 1:
            raise ValueError("capture timeline does not cover its clip")
        selected = times[first:last]
        if not selected or not all(C.number(t) for t in selected) or any(b <= a or b - a > S.MAX_SAMPLE_GAP for a, b in zip(selected, selected[1:])):
            raise ValueError("capture has a live-time discontinuity; split/review it before scoring in clip seconds")
        path = (folder / clip["file"]).resolve()
        path.relative_to(folder)              # malformed metadata must not select another capture
        out[f"clip{index}"] = {"path": path, "expected_seconds": end - start,
                               "capture": {"recording_start": start, "recording_end": end,
                                           "live_start": selected[0], "recorded_fps": fps}}
    if not out:
        raise ValueError("capture contains no clips")
    return out


def frames(path, ffmpeg, fps):
    import numpy as np

    inputs = ["-f", "concat", "-safe", "0"] if Path(path).suffix.lower() == ".ffconcat" else []
    command = [str(ffmpeg), "-v", "error", "-nostdin", "-threads", "1", *inputs, "-i", str(path),
               "-vf", f"fps={fps},scale=1280:720", "-f", "rawvideo", "-pix_fmt", "rgb24", "-"]
    # A file avoids stderr pipe deadlocks while a long recording is decoded.
    with tempfile.TemporaryFile() as errors:
        process = subprocess.Popen(command, stdout=subprocess.PIPE, stderr=errors, stdin=subprocess.DEVNULL,
                                   creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0)
        size, index = 1280 * 720 * 3, 0
        try:
            while True:
                chunks, remaining = [], size
                while remaining:
                    chunk = process.stdout.read(remaining)
                    if not chunk:
                        break
                    chunks.append(chunk)
                    remaining -= len(chunk)
                if remaining:
                    if remaining != size:
                        raise ValueError(f"FFmpeg produced an incomplete RGB frame for {path}")
                    break
                frame = np.frombuffer(b"".join(chunks), dtype=np.uint8).reshape(720, 1280, 3)
                yield index / fps, frame
                index += 1
            returncode = process.wait()
            if returncode:
                errors.seek(0)
                raise ValueError(f"FFmpeg failed ({returncode}) for {path}: {errors.read().decode('utf-8', errors='replace')[-2000:]}")
            if not index:
                raise ValueError(f"FFmpeg decoded no frames from {path}")
        finally:
            if process.poll() is None:
                process.terminate()
                try:
                    process.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    process.kill()
                    process.wait()
            process.stdout.close()


def extract(path, ffmpeg, capture=None, expected_seconds=None):
    from fortnite_chest_counter import match_cues as M
    from importlib.metadata import version

    path = Path(path).resolve()
    files = playlist_files(path)
    inputs = [{"path": str(p), "size": p.stat().st_size, "sha256": sha256(p)} for p in files]
    # Match M1's sample selection exactly: clips decoded at 2 fps, take each even
    # output frame; standalone references decoded at 1 fps. fps=1 on a clip
    # chooses different source pictures (FFmpeg's sampling phase matters).
    fps = 2 if path.suffix.lower() == ".ffconcat" else 1
    reader, previous, samples = M.CueReader(), None, []
    iterator = frames(path, ffmpeg, fps)
    try:
        for index, (t, frame) in enumerate(iterator):
            if index % fps:
                continue
            scores = reader.read(frame)
            picture = M.picture_evidence(frame, previous)
            samples.append([t, scores, M.health_bar_pixels(frame), int(picture.black), int(picture.frozen)])
            previous = picture.sample
    finally:
        iterator.close()
    if not samples:
        raise ValueError(f"no sampled frames: {path}")
    finish = samples[-1][0] + 1
    if expected_seconds is not None and abs(finish - expected_seconds) > 1:
        raise ValueError(f"decoded {finish} s but capture metadata expects {expected_seconds} s")
    cue_files = [Path(M.__file__), ROOT / "src/fortnite_chest_counter/detection/visual.py", *sorted(M.TEMPLATE_DIR.glob("*.npy"))]
    provenance = {"kind": "video_decode", "inputs": inputs, "clock": "clip_video_seconds", "decode_fps": fps, "sample_fps": 1,
                  "ffmpeg_sha256": sha256(ffmpeg), "numpy": version("numpy"), "scipy": version("scipy"),
                  "reader_files": {p.relative_to(ROOT).as_posix(): sha256(p) for p in cue_files}}
    if capture is not None:
        provenance["capture"] = capture
    return {"samples": samples, "finish_t": finish, "provenance": provenance}


def load_chests(path):
    path = Path(path)
    if path.suffix == ".jsonl":
        rows = [json.loads(line) for line in path.read_text(encoding="utf-8-sig").splitlines() if line.strip()]
        rows = [row for row in rows if "time" in row and "certain_counted" in row and "approx_counted" in row]
    else:
        rows = load_json(path)
    validate_chests(rows)
    return rows


def validate_chests(rows):
    if not isinstance(rows, list):
        raise ValueError("chest evidence must be an event list")
    for row in rows:
        if not isinstance(row, dict) or not C.number(row.get("time")) or row["time"] < 0:
            raise ValueError("chest events need a finite nonnegative time")
        if not all(isinstance(row.get(k), bool) for k in ("certain_counted", "approx_counted")):
            raise ValueError("chest events need independent certain_counted and approx_counted booleans")
        if row["certain_counted"] and not row["approx_counted"]:
            raise ValueError("invalid chest evidence: APPROX must include CERTAIN; input is not repaired")
        if "available_t" in row and (not C.number(row["available_t"]) or row["available_t"] < row["time"]):
            raise ValueError("chest available_t must be finite and no earlier than onset time")


def chest_totals(events):
    return {language: {"certain": sum(e["certain_counted"] for e in events if S.chest_language(e.get("popup_template")) == language),
                       "approx": sum(e["approx_counted"] for e in events if S.chest_language(e.get("popup_template")) == language)}
            for language in ("en", "pt", "unknown")}


def replay(source, chests=(), chest_delay=3.0):
    rows = validate_rows(source["samples"], "replay")
    validate_chests(list(chests))
    if not C.number(chest_delay) or chest_delay < 0:
        raise ValueError("chest delay must be finite and nonnegative")
    finish = source.get("finish_t", rows[-1][0] + 1)
    if not C.number(finish) or finish < rows[-1][0]:
        raise ValueError("finish time precedes last observation")
    if any(not rows[0][0] <= event["time"] < finish for event in chests):
        raise ValueError("chest event lies outside the source interval; evidence must use the same clip clock")
    evidence = [{"event_index": i, "event": dict(event), "language": S.chest_language(event.get("popup_template")),
                 "available_t": event.get("available_t", event["time"] + chest_delay),
                 "availability": "recorded" if "available_t" in event else "assumed_onset_plus_delay",
                 "delivered_t": None, "delivery_match": None, "delivery_state": None}
                for i, event in enumerate(chests)]
    waiting = sorted((e for e in evidence if e["event"]["certain_counted"] or e["event"]["approx_counted"]), key=lambda e: (e["available_t"], e["event_index"]))
    machine, events, cursor = S.MatchStateMachine(), [], 0
    for t, scores, health, black, frozen in rows:
        ready = []
        while cursor < len(waiting) and waiting[cursor]["available_t"] <= t:
            ready.append(waiting[cursor])
            cursor += 1
        events.extend(machine.update(S.Observation(t, scores, health, bool(black), bool(frozen), tuple(e["language"] for e in ready))))
        for item in ready:
            item.update(delivered_t=t, delivery_match=machine.open_match_number, delivery_state=machine.state,
                        picture_usable=not (black or frozen))
    events.extend(machine.finish(finish))
    records = [e.to_dict() for e in events if isinstance(e, S.MatchRecord)]
    for record in records:
        # M2's evidence set iteration is not stable across Python hash seeds.
        record["evidence"] = sorted(record["evidence"], key=lambda item: (item[0], item[1]))
    transitions = [asdict(e) for e in events if isinstance(e, S.Transition) and e.reason != S.STOPPED]
    for item in evidence:
        t = item["event"]["time"]
        item["interval_matches"] = [r["match_number"] for r in records if r["opened_t"] <= t < r["closed_t"]]
    return {"records": records, "transitions": transitions,
            "samples": len(rows), "finish_t": finish, "provenance": source.get("provenance", {}),
            "chest_evidence": evidence, "chest_totals": chest_totals(chests), "assumed_chest_delay_seconds": chest_delay,
            "chest_attribution_note": "interval_matches and delivery_match are diagnostic associations, not confirmed own-player credit; raw events and unknown language are preserved"}


def score(sources, truth, chest_inputs=None, allow_provisional=False, chest_delay=3.0):
    C.validate_truth(truth)
    if set(sources) != set(truth["sources"]):
        raise ValueError(f"source IDs differ: evidence={sorted(sources)}, truth={sorted(truth['sources'])}; use --source for an explicit subset")
    chest_inputs = chest_inputs or {}
    if set(chest_inputs) - set(sources):
        raise ValueError("chest evidence names a source that is not being scored")
    results = {}
    for name, source in sources.items():
        prediction = replay(source, chest_inputs.get(name, []), chest_delay)
        results[name] = {"prediction": prediction, "score": C.compare_source(prediction, truth["sources"][name], allow_provisional)}
    counts = {key: sum(result["score"]["counts"][key] for result in results.values()) for key in C.COUNTS}
    reviewed = all(result["score"]["human_reviewed"] for result in results.values())
    return {"schema": REPORT_SCHEMA, "passed": not any(counts.values()), "human_reviewed": reviewed,
            "validation_level": "human_reviewed" if reviewed else "provisional", "counts": counts, "sources": results,
            "state_machine_sha256": sha256(S.__file__), "scope": "each source is independent; repeated footage across clips is not deduplicated into a unique-match total"}


def print_report(report):
    print("MATCH REPLAY SCORECARD (research only)")
    for name, result in report["sources"].items():
        prediction, scored = result["prediction"], result["score"]
        classified = ", ".join(f"{n} {c}" for c, n in scored["classifications"].items())
        print(f"{name}: {len(prediction['records'])} matches ({classified}); {'PASS' if scored['passed'] else 'FAIL'}")
        for kind, items in scored["issues"].items():
            if items:
                print(f"  {kind}: {len(items)}")
                for item in items[:5]:
                    print("    " + json.dumps(item, sort_keys=True))
    status = "PASS" if report["passed"] else "FAIL"
    print(f"RESULT: {status} ({report['validation_level']}; {len(report['sources'])} independent sources)")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--timelines", type=Path, help="existing cue cache (.json or .json.gz); never decodes video")
    parser.add_argument("--video", action="append", default=[], metavar="SOURCE=PATH", help="standalone video or local capture playlist")
    parser.add_argument("--capture", type=Path, help="capture folder; its clips become clip1, clip2, ... (separate machines)")
    parser.add_argument("--truth", required=True, type=Path, help="match-truth-v1 annotations")
    parser.add_argument("--source", nargs="+", help="explicit subset of source IDs")
    parser.add_argument("--chests", action="append", default=[], metavar="SOURCE=PATH", help="frozen chest events (.json/.jsonl) in the same clip clock")
    parser.add_argument("--chest-delay", type=float, default=3.0, help="assumed evidence delivery delay when available_t is absent (default: M2's 3 s)")
    parser.add_argument("--ffmpeg", default="ffmpeg", help="exact FFmpeg executable to use for new decoding")
    parser.add_argument("--write-timelines", type=Path, help="save evidence with provenance for future fast replays")
    parser.add_argument("--out", required=True, type=Path, help="write a detailed JSON scorecard")
    parser.add_argument("--allow-provisional", action="store_true", help="exploratory scoring of explicitly provisional annotations; never marks them human-reviewed")
    args = parser.parse_args(argv)
    try:
        if bool(args.timelines) == bool(args.video or args.capture):
            raise ValueError("choose --timelines OR --video/--capture")
        if not C.number(args.chest_delay) or args.chest_delay < 0:
            raise ValueError("--chest-delay must be finite and nonnegative")
        truth = C.validate_truth(load_json(args.truth))
        chest_paths = named_paths(args.chests)
        inputs = {name: {"path": path} for name, path in named_paths(args.video).items()}
        if args.capture:
            captured = capture_sources(args.capture)
            if set(captured) & set(inputs):
                raise ValueError("video IDs conflict with capture clip IDs")
            inputs.update(captured)
        sources = load_timelines(args.timelines) if args.timelines else inputs
        if args.source:
            selected = set(args.source)
            if len(selected) != len(args.source) or selected - set(sources) or selected - set(truth["sources"]):
                raise ValueError("--source must list unique IDs present in both evidence and truth")
            sources = {k: v for k, v in sources.items() if k in selected}
            truth = {**truth, "sources": {k: v for k, v in truth["sources"].items() if k in selected}}
            if set(chest_paths) - selected:
                raise ValueError("--chests includes a source outside the explicit selection")
        if set(sources) != set(truth["sources"]):
            raise ValueError("evidence and truth source IDs differ; name all inputs or use --source")
        outputs = [p.resolve() for p in (args.out, args.write_timelines) if p is not None]
        protected = {p.resolve() for p in [args.truth, *chest_paths.values(), *[v['path'] for v in inputs.values()]]}
        if args.timelines:
            protected.add(args.timelines.resolve())
        if len(set(outputs)) != len(outputs) or set(outputs) & protected:
            raise ValueError("output paths must be distinct and must not overwrite inputs")
        chests = {name: load_chests(path) for name, path in chest_paths.items()}
        if not args.timelines:
            executable = shutil.which(args.ffmpeg)
            if executable is None:
                raise ValueError(f"FFmpeg not found: {args.ffmpeg}")
            decoded = {}
            for name, source in sources.items():
                print(f"Decoding {name}: {source['path']}", flush=True)
                decoded[name] = extract(ffmpeg=executable, **source)
                print(f"  {len(decoded[name]['samples'])} cue samples", flush=True)
            sources = decoded
        report = score(sources, truth, chests, args.allow_provisional, args.chest_delay)
        report["truth_sha256"] = sha256(args.truth)
        report["chest_input_sha256"] = {name: sha256(path) for name, path in chest_paths.items()}
        if args.write_timelines:
            write_json(args.write_timelines, {"schema": CACHE_SCHEMA, "sources": sources})
        write_json(args.out, report)
        print_report(report)
        return 0 if report["passed"] else 1
    except (ValueError, OSError, KeyError, TypeError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
